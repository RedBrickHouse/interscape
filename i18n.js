  const supportsLanguage = (lang) => Object.prototype.hasOwnProperty.call(translations, lang);
  let currentLanguage = 'ko';

  function t(key, lang = currentLanguage) {
    const dictionary = supportsLanguage(lang) ? translations[lang] : translations.ko;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) return dictionary[key];
    return Object.prototype.hasOwnProperty.call(translations.ko, key) ? translations.ko[key] : key;
  }

  function setLanguage(lang) {
    if (!supportsLanguage(lang)) return currentLanguage;
    currentLanguage = lang;
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const key = element.getAttribute('data-i18n');
      if (Object.prototype.hasOwnProperty.call(translations.ko, key)) element.innerHTML = t(key);
    });
    [['data-i18n-aria', 'aria-label'], ['data-i18n-alt', 'alt']].forEach(([marker, attribute]) => {
      document.querySelectorAll(`[${marker}]`).forEach((element) => {
        const key = element.getAttribute(marker);
        if (Object.prototype.hasOwnProperty.call(translations.ko, key)) element.setAttribute(attribute, t(key));
      });
    });
    document.querySelectorAll('[data-lang]').forEach((button) => {
      button.setAttribute('aria-pressed', String(button.getAttribute('data-lang') === lang));
    });

    document.title = t('docTitle');
    [
      ['meta[name="description"]', 'metaDescription'],
      ['meta[property="og:title"]', 'ogTitle'],
      ['meta[property="og:description"]', 'ogDescription']
    ].forEach(([selector, key]) => {
      const meta = document.querySelector(selector);
      if (meta) meta.setAttribute('content', t(key));
    });

    try {
      window.localStorage.setItem(storageKey, lang);
    } catch (_) {
      // Language switching also works when browser storage is unavailable.
    }
    try {
      const url = new URL(window.location.href);
      if (url.searchParams.has('lang')) {
        url.searchParams.set('lang', lang);
        window.history.replaceState(window.history.state, '', url);
      }
    } catch (_) {
      // A local file preview may not allow history updates.
    }

    document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
    return currentLanguage;
  }

  window.InterscapeI18n = { setLanguage, t, getLanguage: () => currentLanguage };
  window.setLang = setLanguage;

  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.getAttribute('data-lang')));
  });

  let initialLanguage = new URLSearchParams(window.location.search).get('lang');
  if (!supportsLanguage(initialLanguage)) {
    try {
      initialLanguage = window.localStorage.getItem(storageKey);
    } catch (_) {
      initialLanguage = null;
    }
  }
  setLanguage(supportsLanguage(initialLanguage) ? initialLanguage : 'ko');
